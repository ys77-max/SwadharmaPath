"""Regenerates the generated seed SQL.

    python3 supabase/seed/build_seed.py

* supabase/migrations/001_init.sql: everything after the "-- BEGIN GENERATED SEED" marker
  (the first 20 careers, 8 CBSE streams and the instruments) is replaced.
* supabase/migrations/003_library_expansion.sql is rewritten with the rest of the library
  (library_more.py). Each row is inserted only when no career / stream of that name exists,
  so the migration is safe on a database where admins have already edited the library.
* supabase/migrations/005_assessment_battery.sql is rewritten with the v0.2 battery
  (instruments_v2.py): junior, standard and adult versions. It retires the 0.1 placeholders.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from instruments import all_instruments  # noqa: E402
import instruments_v2  # noqa: E402
from library import CAREERS_V1, MORE_CAREERS, MORE_STREAMS, OUTLOOK_SOURCE, SEED_SOURCE, STREAMS_V1  # noqa: E402

MIGRATION = HERE.parent / "migrations" / "001_init.sql"
EXPANSION = HERE.parent / "migrations" / "003_library_expansion.sql"
BATTERY = HERE.parent / "migrations" / "005_assessment_battery.sql"
MARKER = "-- BEGIN GENERATED SEED (supabase/seed/build_seed.py)"


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    raise TypeError(v)


def js(v):
    return lit(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def text_array(xs):
    return "array[" + ", ".join(lit(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


def num_array(xs):
    return "array[" + ", ".join(repr(x) for x in xs) + "]::numeric[]"


def career_sql(c, only_new=False):
    cols = ("    description, day_in_life, typical_entry_paths, india_salary_band, outlook, automation_exposure, adjacent_emerging, sources, last_reviewed)\n")
    vals = (f"{lit(c['name'])}, {lit(c['family'])}, {lit(c['riasec_code'])}, {num_array(c['interest_weights'])},\n"
            f"    {js(c['aptitude_min'])}, {js(c['workstyle_fit'])}, {js(c['values_fit'])},\n"
            f"    {lit(c['description'])},\n    {lit(c['day_in_life'])},\n"
            f"    {js(c['typical_entry_paths'])}, {js(c['india_salary_band'])}, {lit(c['outlook'])}, {lit(c['automation_exposure'])},\n"
            f"    {text_array(c['adjacent_emerging'])}, {js({'content': SEED_SOURCE, 'outlook': OUTLOOK_SOURCE})}, null")
    head = ("with c as (\n  insert into public.careers (name, family, riasec_code, interest_weights, aptitude_min, workstyle_fit, values_fit,\n" + cols)
    if only_new:
        head += f"  select {vals}\n  where not exists (select 1 from public.careers where name = {lit(c['name'])})\n"
    else:
        head += f"  values ({vals})\n"
    out = [head + "  returning id)\n"
           "insert into public.education_pathways (career_id, level, stream_required, exams, degrees, institutions, duration, alternative_routes, notes)\nselect c.id, v.* from c, (values"]
    rows = [f"  ({lit(p['level'])}, {lit(p['stream_required'])}, {js(p['exams'])}, {text_array(p['degrees'])}, "
            f"{js(p['institutions'])}, {lit(p['duration'])}, {lit(p['alternative_routes'])}, {lit(p['notes'])})" for p in c["pathways"]]
    out.append(",\n".join(rows) + "\n) as v(level, stream_required, exams, degrees, institutions, duration, alternative_routes, notes);\n")
    return "\n".join(out)


def stream_row(s):
    return (f"  ({lit(s['name'])}, {lit(s['board'])}, {text_array(s['subjects'])}, {text_array(s['keeps_open'])}, "
            f"{text_array(s['closes'])}, {lit(s['notes'])})")


def build():
    out = [MARKER, "", "-- Career library (20) with education pathways"]
    out += [career_sql(c) for c in CAREERS_V1]
    out.append("-- CBSE stream options (8)")
    out.append("insert into public.stream_options (name, board, subjects, keeps_open_families, closes_families, notes) values")
    out.append(",\n".join(stream_row(s) for s in STREAMS_V1) + ";\n")

    out.append("-- Instruments: one junior and one standard version each (placeholder items)")
    for i in all_instruments():
        out.append("insert into public.instruments (code, name, version, track_variant, items, scoring_spec, norms, time_limit_min, is_active) values\n"
                   f"  ({lit(i['code'])}, {lit(i['name'])}, {lit(i['version'])}, {lit(i['track_variant'])},\n"
                   f"   {js(i['items'])},\n   {js(i['scoring_spec'])},\n   {js(i['norms'])}, {lit(i['time_limit_min'])}, true);\n")
    return "\n".join(out)


def build_expansion():
    out = ["-- 003 Library expansion. GENERATED by supabase/seed/build_seed.py from supabase/seed/library_more.py; do not edit by hand.",
           f"-- Adds {len(MORE_CAREERS)} careers (with education pathways) and {len(MORE_STREAMS)} stream options for CBSE, CISCE,",
           "-- state boards, NIOS, IB, Cambridge and the after-Class-10 polytechnic and ITI routes.",
           "-- A row is skipped when the library already has a career / stream with that name, so admin edits are kept.",
           "-- New rows are seed content (last_reviewed null): the quarterly refresh or a CSV review verifies them.",
           "", "begin;", ""]
    out += [career_sql(c, only_new=True) for c in MORE_CAREERS]
    out.append("insert into public.stream_options (name, board, subjects, keeps_open_families, closes_families, notes, sources)")
    out.append("select v.name, v.board, v.subjects, v.keeps_open_families, v.closes_families, v.notes, "
               + js(SEED_SOURCE) + "\nfrom (values")
    out.append(",\n".join(stream_row(s) for s in MORE_STREAMS))
    out.append(") as v(name, board, subjects, keeps_open_families, closes_families, notes)\n"
               "where not exists (select 1 from public.stream_options o where o.name = v.name);\n")
    out.append("commit;\n")
    return "\n".join(out)


CODES = ["interest", "subject_enjoyment", "aptitude", "bigfive", "workstyle", "values", "school_values", "learning",
         "career_anchors", "adaptability"]


def build_battery():
    insts = instruments_v2.all_instruments()
    counts = {}
    for i in insts:
        counts[i["track_variant"]] = counts.get(i["track_variant"], 0) + instruments_v2.item_count(i)
    out = ["-- 005 Assessment battery v0.2. GENERATED by supabase/seed/build_seed.py from supabase/seed/instruments_v2.py; do not edit by hand.",
           "-- Three versions tailored to the objective: junior (Class 8-10, stream choice, "
           f"{counts['junior']} questions), standard (Class 11-12, course and career, {counts['standard']}),",
           f"-- adult (professionals, career growth or change, {counts['adult']}). Adds the adult variant and the career_anchors and",
           "-- adaptability instruments, retires the 0.1 placeholders (their sessions and results stay) and maps",
           "-- track professional to the adult variant in my_instruments.",
           "", "begin;", "",
           "alter table public.instruments drop constraint if exists instruments_code_check;",
           "alter table public.instruments add constraint instruments_code_check check (code in ("
           + ", ".join(lit(c) for c in CODES) + "));",
           "alter table public.instruments drop constraint if exists instruments_track_variant_check;",
           "alter table public.instruments add constraint instruments_track_variant_check check (track_variant in ('junior','standard','adult'));",
           "",
           "update public.instruments set is_active = false where version = '0.1-placeholder';",
           ""]
    for i in insts:
        out.append("insert into public.instruments (code, name, version, track_variant, items, scoring_spec, norms, time_limit_min, is_active)\n"
                   f"select {lit(i['code'])}, {lit(i['name'])}, {lit(i['version'])}, {lit(i['track_variant'])},\n"
                   f"   {js(i['items'])},\n   {js(i['scoring_spec'])},\n   {js(i['norms'])}, {lit(i['time_limit_min'])}, true\n"
                   f"where not exists (select 1 from public.instruments where code = {lit(i['code'])} and track_variant = {lit(i['track_variant'])}"
                   f" and version = {lit(i['version'])});\n")
    out.append("""-- Instruments for the caller's track, with their latest session.
create or replace function public.my_instruments()
returns table (instrument_id uuid, code text, name text, track_variant text, time_limit_min int,
               item_count int, est_minutes int, session_id uuid, status text, answered int)
language sql stable security definer set search_path = '' as $$
  with me as (
    select c.id, private.track_variant(c.track) as variant
    from public.candidates c where c.user_id = auth.uid() order by c.created_at desc limit 1
  )
  select i.id, i.code, i.name, i.track_variant, i.time_limit_min,
         (select count(*) from jsonb_array_elements(i.items->'sections') s, jsonb_array_elements(s->'items'))::int,
         coalesce(i.time_limit_min, ceil((select count(*) from jsonb_array_elements(i.items->'sections') s,
                                                jsonb_array_elements(s->'items')) * 12 / 60.0)::int),
         a.id, a.status,
         (select count(*) from jsonb_object_keys(coalesce(a.responses, '{}'::jsonb) - '_meta'))::int
  from me join public.instruments i on i.track_variant = me.variant and i.is_active
  left join lateral (
    select * from public.assessment_sessions x
    where x.candidate_id = me.id and x.instrument_id = i.id and x.status <> 'invalidated'
    order by x.started_at desc nulls last limit 1
  ) a on true
  order by array_position(array[""" + ", ".join(lit(c) for c in CODES) + """], i.code)
$$;
""")
    helper = """-- Which instrument variant a track takes.
create or replace function private.track_variant(p_track text) returns text
language sql immutable set search_path = '' as $$
  select case p_track when 'early_explorer' then 'junior' when 'professional' then 'adult' else 'standard' end
$$;
grant execute on function private.track_variant(text) to anon, authenticated, service_role;
"""
    out.insert(out.index("begin;") + 2, helper)
    out.append("commit;\n")
    return "\n".join(out)


def main():
    sql = MIGRATION.read_text()
    head = sql.split(MARKER)[0].rstrip() + "\n\n"
    MIGRATION.write_text(head + build())
    EXPANSION.write_text(build_expansion())
    BATTERY.write_text(build_battery())
    print(f"wrote seed block to {MIGRATION}, {EXPANSION} and {BATTERY}")


if __name__ == "__main__":
    main()
